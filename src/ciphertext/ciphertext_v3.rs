//! Ciphertext V3 (FIPS): AES-256-GCM
//!
//! Symmetric payload layout (after the 8-byte header):
//! ```text
//! [ salt (32) ][ nonce (12) ][ ciphertext || tag (16) ]
//! ```
//! The encryption key is derived for each message with HKDF-SHA256 using a random salt, so the
//! 96-bit GCM IV, generated inside the module, never has to be unique across messages.
//!
//! Asymmetric payload layout:
//! ```text
//! [ ephemeral P-256 public key (65) ][ symmetric payload ]
//! ```
//! The HKDF input is the ECDH shared secret, and both public keys are bound in the HKDF info.
use super::{PrivateKey, PublicKey};

use super::Error;
use super::Header;
use super::Result;

use super::Ciphertext;

use crate::key::{KeyV3Private, KeyV3Public};

use std::convert::TryFrom;

use aws_lc_rs::aead::{AES_256_GCM, Aad, NONCE_LEN, Nonce, RandomizedNonceKey};
use aws_lc_rs::agreement::{self, ECDH_P256};
use aws_lc_rs::hkdf::{HKDF_SHA256, KeyType, Salt};
use zeroize::{Zeroize, Zeroizing};

const SALT_LEN: usize = 32;
const KEY_LEN: usize = 32;
const TAG_LEN: usize = 16;

const SYMMETRIC_INFO: &[u8] = b"DevolutionsCrypto Ciphertext V3 symmetric";
const ASYMMETRIC_INFO: &[u8] = b"DevolutionsCrypto Ciphertext V3 asymmetric";

#[derive(Zeroize, Clone, Debug)]
#[zeroize(drop)]
pub struct CiphertextV3Symmetric {
    salt: [u8; SALT_LEN],
    nonce: [u8; NONCE_LEN],
    ciphertext: Vec<u8>,
}

#[derive(Clone, Debug)]
pub struct CiphertextV3Asymmetric {
    public_key: KeyV3Public,
    ciphertext: CiphertextV3Symmetric,
}

struct Len(usize);

impl KeyType for Len {
    fn len(&self) -> usize {
        self.0
    }
}

impl From<CiphertextV3Symmetric> for Vec<u8> {
    fn from(mut cipher: CiphertextV3Symmetric) -> Vec<u8> {
        let mut data = Vec::with_capacity(SALT_LEN + NONCE_LEN + cipher.ciphertext.len());
        data.extend_from_slice(&cipher.salt);
        data.extend_from_slice(&cipher.nonce);
        data.append(&mut cipher.ciphertext);
        data
    }
}

impl TryFrom<&[u8]> for CiphertextV3Symmetric {
    type Error = Error;
    fn try_from(data: &[u8]) -> Result<Self> {
        if data.len() < SALT_LEN + NONCE_LEN + TAG_LEN {
            return Err(Error::InvalidLength);
        };

        let mut salt = [0u8; SALT_LEN];
        let mut nonce = [0u8; NONCE_LEN];

        salt.copy_from_slice(&data[..SALT_LEN]);
        nonce.copy_from_slice(&data[SALT_LEN..SALT_LEN + NONCE_LEN]);
        let ciphertext = data[SALT_LEN + NONCE_LEN..].to_vec();

        Ok(CiphertextV3Symmetric {
            salt,
            nonce,
            ciphertext,
        })
    }
}

impl CiphertextV3Symmetric {
    fn derive_key(secret: &[u8], salt: &[u8], info: &[&[u8]]) -> Result<RandomizedNonceKey> {
        let mut key = Zeroizing::new([0u8; KEY_LEN]);

        Salt::new(HKDF_SHA256, salt)
            .extract(secret)
            .expand(info, Len(KEY_LEN))?
            .fill(key.as_mut_slice())?;

        Ok(RandomizedNonceKey::new(&AES_256_GCM, key.as_slice())?)
    }

    fn mac_data(header: &Header<Ciphertext>, aad: &[u8]) -> Zeroizing<Vec<u8>> {
        // Authenticate the header
        let mut mac_data: Zeroizing<Vec<u8>> = Zeroizing::new(header.into());
        mac_data.extend_from_slice(aad);
        mac_data
    }

    pub fn encrypt(
        data: &[u8],
        key: &[u8],
        aad: &[u8],
        header: &Header<Ciphertext>,
    ) -> Result<Self> {
        Self::encrypt_with_info(data, key, &[SYMMETRIC_INFO], aad, header)
    }

    fn encrypt_with_info(
        data: &[u8],
        secret: &[u8],
        info: &[&[u8]],
        aad: &[u8],
        header: &Header<Ciphertext>,
    ) -> Result<Self> {
        let mut salt = [0u8; SALT_LEN];
        crate::utils::fill_random(&mut salt)?;

        let key = Self::derive_key(secret, &salt, info)?;
        let mac_data = Self::mac_data(header, aad);

        // The IV is generated by the module
        let mut ciphertext = data.to_vec();
        let nonce =
            key.seal_in_place_append_tag(Aad::from(mac_data.as_slice()), &mut ciphertext)?;

        Ok(CiphertextV3Symmetric {
            salt,
            nonce: *nonce.as_ref(),
            ciphertext,
        })
    }

    pub fn decrypt(&self, key: &[u8], aad: &[u8], header: &Header<Ciphertext>) -> Result<Vec<u8>> {
        self.decrypt_with_info(key, &[SYMMETRIC_INFO], aad, header)
    }

    fn decrypt_with_info(
        &self,
        secret: &[u8],
        info: &[&[u8]],
        aad: &[u8],
        header: &Header<Ciphertext>,
    ) -> Result<Vec<u8>> {
        let key = Self::derive_key(secret, &self.salt, info)?;
        let mac_data = Self::mac_data(header, aad);

        let mut buffer = Zeroizing::new(self.ciphertext.clone());
        let plaintext = key
            .open_in_place(
                Nonce::assume_unique_for_key(self.nonce),
                Aad::from(mac_data.as_slice()),
                buffer.as_mut_slice(),
            )
            .map_err(|_| Error::InvalidMac)?;

        Ok(plaintext.to_vec())
    }
}

impl From<CiphertextV3Asymmetric> for Vec<u8> {
    fn from(cipher: CiphertextV3Asymmetric) -> Self {
        let mut data: Vec<u8> = cipher.public_key.into();
        let mut ciphertext = cipher.ciphertext.into();
        data.append(&mut ciphertext);
        data
    }
}

impl TryFrom<&[u8]> for CiphertextV3Asymmetric {
    type Error = Error;
    fn try_from(data: &[u8]) -> Result<Self> {
        let public_key_len = crate::key::P256_PUBLIC_KEY_LENGTH;

        if data.len() <= public_key_len {
            return Err(Error::InvalidLength);
        };

        let public_key = KeyV3Public::try_from(&data[..public_key_len])?;
        let ciphertext = CiphertextV3Symmetric::try_from(&data[public_key_len..])?;

        Ok(CiphertextV3Asymmetric {
            public_key,
            ciphertext,
        })
    }
}

impl CiphertextV3Asymmetric {
    pub fn encrypt(
        data: &[u8],
        public_key: &PublicKey,
        aad: &[u8],
        header: &Header<Ciphertext>,
    ) -> Result<Self> {
        let recipient_public_key = public_key.to_p256()?;

        let ephemeral_private_key = agreement::PrivateKey::generate(&ECDH_P256)?;
        let ephemeral_public_key =
            crate::key::p256_public_from_agreement_key(&ephemeral_private_key)?;

        let info = [
            ASYMMETRIC_INFO,
            ephemeral_public_key.as_bytes(),
            recipient_public_key.as_bytes(),
        ];

        let ciphertext = agreement::agree(
            &ephemeral_private_key,
            recipient_public_key.to_unparsed(),
            Error::InvalidData,
            |shared| CiphertextV3Symmetric::encrypt_with_info(data, shared, &info, aad, header),
        )?;

        Ok(Self {
            public_key: ephemeral_public_key,
            ciphertext,
        })
    }

    pub fn decrypt(
        &self,
        private_key: &PrivateKey,
        aad: &[u8],
        header: &Header<Ciphertext>,
    ) -> Result<Vec<u8>> {
        let private_key: &KeyV3Private = private_key.to_p256()?;
        let recipient_public_key = private_key.compute_public_key()?;

        let info = [
            ASYMMETRIC_INFO,
            self.public_key.as_bytes(),
            recipient_public_key.as_bytes(),
        ];

        agreement::agree(
            &private_key.to_agreement_key()?,
            self.public_key.to_unparsed(),
            Error::InvalidData,
            |shared| {
                self.ciphertext
                    .decrypt_with_info(shared, &info, aad, header)
            },
        )
    }
}
